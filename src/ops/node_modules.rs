//! node_modules sweep: delete only in repos/projects with no recent commits.
//! Active repos (commits within `active_days`) are skipped and reported.

use anyhow::Result;
use colored::Colorize;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use super::{Finding, Op, Summary, dir_size, remove_path};
use crate::safety::{Ctx, escalate};

pub struct NodeModules;

impl Op for NodeModules {
    fn name(&self) -> &'static str {
        "node-modules"
    }
    fn scan(&self, ctx: &Ctx) -> Result<Vec<Finding>> {
        let cutoff = iso_days_ago(ctx.active_days);
        // owner root -> all node_modules under it
        let mut groups: BTreeMap<PathBuf, Vec<PathBuf>> = BTreeMap::new();
        for root in &ctx.roots {
            if !root.is_dir() {
                continue;
            }
            for nm in find_node_modules(root) {
                groups.entry(owning_repo(&nm)).or_default().push(nm);
            }
        }

        let mut out = Vec::new();
        let mut active_count = 0usize;
        for (owner, nms) in groups {
            if owner == Path::new("(no-repo)") {
                // Unmanaged scratch projects: judge each node_modules dir alone.
                for nm in nms {
                    let size = dir_size(&nm);
                    out.push(stale_finding(&nm, size));
                }
                continue;
            }
            let last = repo_last_commit(&owner);
            let stale = match &last {
                None => true,
                Some(date) => date.as_str() <= cutoff.as_str(),
            };
            if !stale {
                active_count += nms.len();
                continue;
            }
            let total: u64 = nms.iter().map(|p| dir_size(p)).sum();
            // Representative path = first nm; apply re-derives the full set from it.
            let rep = nms[0].clone();
            out.push(stale_finding(&rep, total));
        }
        if active_count > 0 && !ctx.json {
            eprintln!("{} skipping {active_count} node_modules in active repos", "info".dimmed());
        }
        Ok(out)
    }

    fn apply(&self, findings: &[Finding], ctx: &Ctx) -> Result<Summary> {
        let mut notes = Vec::new();
        let mut touched = 0usize;
        let mut bytes = 0u64;
        for f in findings {
            bytes += f.size_bytes;
            let Some(rep) = f.path.as_ref() else { continue };
            let owner = owning_repo(Path::new(rep));
            let targets: Vec<PathBuf> = if owner == Path::new("(no-repo)") {
                vec![PathBuf::from(rep)]
            } else {
                find_node_modules(&owner)
            };
            for nm in &targets {
                remove_path(nm, ctx)?;
                touched += 1;
            }
            notes.push(format!("removed {} node_modules under {}", targets.len(), owner.display()));
        }
        Ok(Summary {
            op: self.name().into(),
            items_touched: touched,
            bytes_freed_estimate: bytes,
            notes,
        })
    }
}

fn stale_finding(rep: &Path, size: u64) -> Finding {
    let owner = owning_repo(rep);
    Finding {
        label: "stale node_modules".into(),
        path: Some(rep.display().to_string()),
        size_bytes: size,
        note: format!(
            "repo inactive ≥ cutoff (lockfile: {}); reinstall with `pnpm install` / `npm install`",
            has_lockfile(&owner)
        ),
        danger: escalate(5, size),
        action: "trash".into(),
    }
}

/// All node_modules under `root`, excluding those nested inside another
/// node_modules (pnpm virtual stores etc.) and .git dirs.
fn find_node_modules(root: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for e in walkdir::WalkDir::new(root)
        .follow_links(false)
        .into_iter()
        .filter_map(|e| e.ok())
    {
        if e.file_type().is_dir() && e.file_name() == "node_modules" && !nested_in_nm(root, e.path())
        {
            found.push(e.path().to_path_buf());
        }
    }
    found
}

fn nested_in_nm(root: &Path, p: &Path) -> bool {
    let mut cur = p.parent();
    while let Some(c) = cur {
        if c == root {
            return false;
        }
        if c.file_name().map(|n| n == "node_modules").unwrap_or(false) {
            return true;
        }
        cur = c.parent();
    }
    false
}

/// Nearest ancestor (inclusive of parents only) containing `.git`.
fn owning_repo(nm: &Path) -> PathBuf {
    let mut cur = nm.to_path_buf();
    while cur.parent().is_some() {
        cur.pop();
        if cur.join(".git").exists() {
            return cur;
        }
    }
    PathBuf::from("(no-repo)")
}

fn repo_last_commit(root: &Path) -> Option<String> {
    if !root.join(".git").exists() {
        return None;
    }
    let out = Command::new("git")
        .arg("-C")
        .arg(root)
        .args(["log", "-1", "--format=%cs"])
        .output()
        .ok()?;
    let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
    if s.is_empty() { None } else { Some(s) }
}

pub(crate) fn has_lockfile(root: &Path) -> &'static str {
    for f in [
        "pnpm-lock.yaml",
        "package-lock.json",
        "yarn.lock",
        "bun.lockb",
        "bun.lock",
    ] {
        if root.join(f).exists() {
            return f;
        }
    }
    "none"
}

fn iso_days_ago(days: u32) -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    iso_from_epoch_days(((secs.saturating_sub(days as u64 * 86_400)) / 86_400) as i64)
}

/// Civil-date conversion (Howard Hinnant's algorithm); no chrono dependency.
fn iso_from_epoch_days(z: i64) -> String {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    format!("{y:04}-{m:02}-{d:02}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn iso_dates_are_correct_and_ordered() {
        assert_eq!(iso_from_epoch_days(0), "1970-01-01");
        assert_eq!(iso_from_epoch_days(19_723), "2024-01-01");
        assert!(iso_days_ago(30) < iso_days_ago(1));
    }

    #[test]
    fn finds_owning_repo_and_handles_orphans() {
        let base = std::env::temp_dir().join(format!("dt-own-{}", std::process::id()));
        let proj = base.join("proj/sub/deep/node_modules");
        std::fs::create_dir_all(&proj).unwrap();
        std::fs::create_dir_all(base.join("proj/.git")).unwrap();
        assert_eq!(owning_repo(&proj), base.join("proj"));
        let orphan = base.join("orphan/node_modules");
        std::fs::create_dir_all(&orphan).unwrap();
        assert_eq!(owning_repo(&orphan), PathBuf::from("(no-repo)"));
        std::fs::remove_dir_all(&base).ok();
    }

    #[test]
    fn skips_nested_virtual_stores() {
        let base = std::env::temp_dir().join(format!("dt-nest-{}", std::process::id()));
        let outer = base.join("app/node_modules");
        let inner = outer.join(".pnpm/x/node_modules/y");
        std::fs::create_dir_all(&inner).unwrap();
        let found = find_node_modules(&base);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0], outer);
        std::fs::remove_dir_all(&base).ok();
    }

    #[test]
    fn lockfile_detection() {
        let base = std::env::temp_dir().join(format!("dt-lf-{}", std::process::id()));
        std::fs::create_dir_all(&base).unwrap();
        std::fs::write(base.join("package-lock.json"), "{}").unwrap();
        assert_eq!(has_lockfile(&base), "package-lock.json");
        assert_eq!(has_lockfile(&base.join("nope")), "none");
        std::fs::remove_dir_all(&base).ok();
    }
}
