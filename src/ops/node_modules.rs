//! `node_modules` sweep for Git repos with a conclusively old last commit.

use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::ffi::OsStr;
use std::os::unix::ffi::OsStrExt;
use std::path::{Component, Path, PathBuf};

use super::{
    Action, ApplyOutcome, Finding, Op, apply_filesystem_finding, dir_size,
    has_node_modules_ancestor, is_node_modules_name, removal_note,
};
use crate::safety::{Ctx, build_process_cwds, escalate, is_git_metadata_name};

use super::project::{
    ScanObservations, has_git_marker, is_directory_if_present, iso_days_ago, normalized_roots,
    owning_repo, repo_has_active_build, repo_last_commit,
};

pub struct NodeModules;

impl Op for NodeModules {
    fn name(&self) -> &'static str {
        "node-modules"
    }

    fn scan(&self, ctx: &Ctx, observations: &ScanObservations) -> Result<Vec<Finding>> {
        observations.process_cwds()?;
        let cutoff = iso_days_ago(ctx.active_days);
        let mut groups: BTreeMap<PathBuf, Vec<PathBuf>> = BTreeMap::new();
        for root in normalized_roots(&ctx.roots) {
            if is_directory_if_present(root)? {
                for path in find_node_modules(root)? {
                    if has_git_marker(&path)? {
                        continue;
                    }
                    if let Some(owner) = owning_repo(&path)? {
                        groups.entry(owner).or_default().push(path);
                    }
                }
            }
        }

        let mut findings = Vec::new();
        let mut active = 0usize;
        let mut build_active = 0usize;
        for (owner, targets) in groups {
            if repo_has_active_build(&owner, observations.process_cwds()?) {
                build_active = build_active.saturating_add(targets.len());
                continue;
            }
            let last_commit = observations.last_commit(&owner)?;
            if last_commit.as_str() > cutoff.as_str() {
                active += targets.len();
                continue;
            }
            for target in targets {
                let size = dir_size(&target)?;
                findings.push(Finding::new(
                    "stale node_modules",
                    Some(target),
                    size,
                    format!(
                        "repo last committed {last_commit}; lockfile: {}",
                        has_lockfile(&owner)
                    ),
                    escalate(5, size),
                    Action::Trash,
                ));
            }
        }
        if active > 0 && !ctx.json {
            ctx.diagnostic(
                "info",
                format!("skipping {active} node_modules in active repos"),
            );
        }
        if build_active > 0 && !ctx.json {
            ctx.diagnostic(
                "info",
                format!("skipping {build_active} node_modules because a build process is active"),
            );
        }
        Ok(findings)
    }

    fn apply(&self, findings: &[Finding], ctx: &Ctx) -> Result<ApplyOutcome> {
        self.apply_with_process_cwds(findings, ctx, build_process_cwds())
    }
}

impl NodeModules {
    #[cfg(test)]
    fn scan_with_process_cwds(&self, ctx: &Ctx, process_cwds: &[PathBuf]) -> Result<Vec<Finding>> {
        self.scan(
            ctx,
            &ScanObservations::with_process_cwds(process_cwds.to_vec()),
        )
    }

    fn apply_with_process_cwds(
        &self,
        findings: &[Finding],
        ctx: &Ctx,
        process_cwds: Result<Vec<PathBuf>>,
    ) -> Result<ApplyOutcome> {
        let cutoff = iso_days_ago(ctx.active_days);
        let mut outcome = ApplyOutcome::new(self.name());
        let process_cwds = match process_cwds {
            Ok(process_cwds) => process_cwds,
            Err(error) => {
                outcome.fail(error.context("cannot verify build-process liveness"));
                return Ok(outcome);
            }
        };
        // Authorize the whole actionable batch before mutating any item. A
        // vanished target is a safe no-op; any other drift rejects the plan.
        let mut ready = Vec::new();
        for finding in findings {
            if !matches!(finding.action, Action::Trash | Action::Shred) {
                continue;
            }
            let Some(path) = finding.target() else {
                outcome.fail(anyhow::anyhow!(
                    "node_modules finding missing internal target"
                ));
                return Ok(outcome);
            };
            match std::fs::symlink_metadata(path) {
                Ok(metadata) if metadata.file_type().is_dir() => {}
                Ok(_) => {
                    outcome.fail(anyhow::anyhow!(
                        "refusing non-directory node_modules target: {}",
                        path.display()
                    ));
                    return Ok(outcome);
                }
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                    outcome
                        .summary
                        .notes
                        .push(format!("skipped vanished {}", path.display()));
                    continue;
                }
                Err(error) => {
                    outcome.fail(anyhow::Error::new(error).context(format!(
                        "cannot inspect node_modules target {}",
                        path.display()
                    )));
                    return Ok(outcome);
                }
            }
            let result = (|| -> Result<()> {
                if has_git_marker(path)? {
                    anyhow::bail!(
                        "target gained its own Git marker after preview; refusing {}",
                        path.display()
                    );
                }
                let owner = owning_repo(path)?.ok_or_else(|| {
                    anyhow::anyhow!("cannot prove Git owner for {}", path.display())
                })?;
                authorize_node_modules_target(path, &owner)?;
                if repo_has_active_build(&owner, &process_cwds) {
                    anyhow::bail!(
                        "build process active in {}; refusing {}",
                        owner.display(),
                        path.display()
                    );
                }
                let last_commit = repo_last_commit(&owner)?;
                if last_commit > cutoff {
                    anyhow::bail!(
                        "repo became active after preview; refusing {}",
                        path.display()
                    );
                }
                Ok(())
            })();
            if let Err(error) = result {
                outcome.fail(error);
                return Ok(outcome);
            }
            ready.push((finding, path));
        }

        for (finding, path) in ready {
            match apply_filesystem_finding(self.name(), finding, ctx) {
                Ok(()) => outcome.record(finding, removal_note(finding, path.display())),
                Err(error) => {
                    outcome.fail(error);
                    break;
                }
            }
        }
        Ok(outcome)
    }
}

fn authorize_node_modules_target(path: &Path, owner: &Path) -> Result<()> {
    reject_non_normal_raw_path(path)?;
    reject_non_normal_raw_path(owner)?;
    reject_symlinked_git_owner(owner, path)?;
    let relative = path.strip_prefix(owner).with_context(|| {
        format!(
            "node_modules target is outside its owning repository: {}",
            path.display()
        )
    })?;
    let components = relative.components().collect::<Vec<_>>();
    let Some((final_component, ancestors)) = components.split_last() else {
        anyhow::bail!("refusing repository root as node_modules target");
    };
    if !matches!(
        final_component,
        Component::Normal(name) if *name == OsStr::new("node_modules")
    ) {
        anyhow::bail!("refusing non-node_modules target: {}", path.display());
    }

    let mut current = owner.to_path_buf();
    for component in ancestors {
        match component {
            Component::Normal(name)
                if !is_git_metadata_name(name) && !is_node_modules_name(name) =>
            {
                current.push(name);
                match std::fs::symlink_metadata(&current) {
                    Ok(metadata) if metadata.file_type().is_symlink() => anyhow::bail!(
                        "refusing node_modules target with symlinked node_modules ancestor: {}",
                        path.display()
                    ),
                    Ok(metadata) if metadata.is_dir() => {}
                    Ok(_) => anyhow::bail!(
                        "refusing node_modules target with non-directory ancestor: {}",
                        path.display()
                    ),
                    Err(error) => {
                        return Err(error).with_context(|| {
                            format!("cannot inspect node_modules ancestor {}", current.display())
                        });
                    }
                }
            }
            _ => anyhow::bail!(
                "refusing node_modules target under an excluded ancestor: {}",
                path.display()
            ),
        }
    }

    if has_node_modules_ancestor(path) {
        anyhow::bail!(
            "refusing node_modules target under an excluded ancestor: {}",
            path.display()
        );
    }

    let owner = owner
        .canonicalize()
        .with_context(|| format!("cannot resolve Git owner {}", owner.display()))?;
    let target = path
        .canonicalize()
        .with_context(|| format!("cannot resolve node_modules target {}", path.display()))?;
    if !target.starts_with(&owner) {
        anyhow::bail!(
            "node_modules target resolves outside its owning repository: {} -> {}",
            path.display(),
            target.display()
        );
    }
    Ok(())
}

fn reject_symlinked_git_owner(owner: &Path, target: &Path) -> Result<()> {
    match std::fs::symlink_metadata(owner) {
        Ok(metadata) if metadata.file_type().is_symlink() => anyhow::bail!(
            "refusing node_modules target with symlinked Git owner: {}",
            target.display()
        ),
        Ok(metadata) if metadata.is_dir() => Ok(()),
        Ok(_) => anyhow::bail!(
            "refusing node_modules target with non-directory Git owner: {}",
            target.display()
        ),
        Err(error) => {
            Err(error).with_context(|| format!("cannot inspect Git owner {}", owner.display()))
        }
    }
}

fn reject_non_normal_raw_path(path: &Path) -> Result<()> {
    for (index, segment) in path
        .as_os_str()
        .as_bytes()
        .split(|byte| *byte == b'/')
        .enumerate()
    {
        if segment.is_empty() {
            if index == 0 && path.is_absolute() {
                continue;
            }
            anyhow::bail!(
                "refusing non-normal node_modules target: {}",
                path.display()
            );
        }
        if segment == b"." || segment == b".." {
            anyhow::bail!(
                "refusing non-normal node_modules target: {}",
                path.display()
            );
        }
    }
    Ok(())
}

fn find_node_modules(root: &Path) -> Result<Vec<PathBuf>> {
    let mut found = Vec::new();
    let mut entries = walkdir::WalkDir::new(root).follow_links(false).into_iter();
    while let Some(result) = entries.next() {
        let entry =
            result.with_context(|| format!("cannot scan node_modules under {}", root.display()))?;
        if !entry.file_type().is_dir() {
            continue;
        }
        if is_git_metadata_name(entry.file_name()) {
            entries.skip_current_dir();
            continue;
        }
        if is_node_modules_name(entry.file_name()) {
            if entry.file_name() == "node_modules" {
                found.push(entry.path().to_path_buf());
            }
            entries.skip_current_dir();
        }
    }
    found.sort();
    Ok(found)
}

pub(crate) fn has_lockfile(root: &Path) -> &'static str {
    for file in [
        "pnpm-lock.yaml",
        "package-lock.json",
        "yarn.lock",
        "bun.lockb",
        "bun.lock",
    ] {
        if root.join(file).exists() {
            return file;
        }
    }
    "none"
}

