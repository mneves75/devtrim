    /// A repository whose checks fail is reported as an error and offers
    /// nothing — not even a finding judged before the failure — while every
    /// other repository is judged as usual. The run still reports the error.
    #[test]
    fn a_failing_repository_blocks_only_its_own_findings() {
        let home = temp("repository-contained");
        let installed = stale_install(&home.join("healthy"));
        let dangling = home.join("dangling");
        stale_install(&dangling);
        for entry in std::fs::read_dir(dangling.join(".git/objects")).unwrap() {
            let entry = entry.unwrap();
            if entry.file_name().len() == 2 {
                std::fs::remove_dir_all(entry.path()).unwrap();
            }
        }
        // Judged in path order: `a` is measured, then `b` fails, so the
        // repository's already-built finding must be withheld with it.
        let partial = home.join("partial");
        init_old_git_repo(&partial).unwrap();
        for package in ["a", "b"] {
            std::fs::create_dir_all(partial.join(package).join("node_modules")).unwrap();
            std::fs::write(partial.join(package).join("package.json"), "{}").unwrap();
        }
        std::fs::write(partial.join("a/node_modules/index.js"), "x").unwrap();
        let unreadable = partial.join("b/node_modules/pkg");
        let _unreadable = crate::ops::Unreadable::new(&unreadable, 0o000);
        let ctx = context(home.clone());

        let findings = NodeModules.scan_with_process_cwds(&ctx, &[]).unwrap();

        assert_eq!(
            offered(&findings),
            vec![installed.as_path()],
            "PV node_modules/repository-contained: a failing repository offered a finding"
        );
        let errors = scan_errors(&findings);
        assert_eq!(errors.len(), 2, "{errors:?}");
        assert!(
            errors
                .iter()
                .any(|error| error.contains(&dangling.display().to_string())),
            "{errors:?}"
        );
        assert!(
            errors
                .iter()
                .any(|error| error.contains(&partial.display().to_string())),
            "{errors:?}"
        );
        assert!(
            findings
                .iter()
                .filter(|finding| finding.scan_error().is_some())
                .all(|finding| finding.action == Action::Info && finding.target().is_none())
        );
        drop(_unreadable);
        crate::ops::remove_test_path(home);
    }

    /// A check that fails once the owning repository is known blocks that
    /// whole repository, as a failure while judging it does: two scan roots
    /// inside one repository must not let one root's findings through while
    /// the other root's candidate could not be checked. Here the build-output
    /// check of `b/x` fails on a `CACHEDIR.TAG` that cannot be opened.
    #[test]
    fn a_failure_after_the_owner_is_known_blocks_the_whole_repository() {
        use std::os::unix::fs::PermissionsExt;

        let home = temp("owner-veto");
        let healthy = stale_install(&home.join("healthy"));
        let repo = home.join("repo");
        init_old_git_repo(&repo).unwrap();
        for package in ["a", "b/x"] {
            std::fs::create_dir_all(repo.join(package).join("node_modules/pkg")).unwrap();
            std::fs::write(repo.join(package).join("package.json"), "{}").unwrap();
        }
        let tag = repo.join("b/x/CACHEDIR.TAG");
        std::fs::write(&tag, "unreadable").unwrap();
        std::fs::set_permissions(&tag, std::fs::Permissions::from_mode(0o000)).unwrap();
        assert!(
            std::fs::File::open(&tag).is_err(),
            "run without privileges that ignore modes"
        );
        let mut ctx = context(home.clone());
        ctx.roots = vec![home.join("healthy"), repo.join("a"), repo.join("b/x")];

        let findings = NodeModules.scan_with_process_cwds(&ctx, &[]);

        std::fs::set_permissions(&tag, std::fs::Permissions::from_mode(0o644)).unwrap();
        let findings = findings.unwrap();
        assert_eq!(
            offered(&findings),
            vec![healthy.as_path()],
            "PV node_modules/owner-veto: a repository with a failed candidate offered another"
        );
        let errors = scan_errors(&findings);
        assert!(
            errors.len() == 1 && errors[0].contains(&repo.display().to_string()),
            "{errors:?}"
        );
        crate::ops::remove_test_path(home);
    }

