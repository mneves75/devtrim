//! `node_modules` sweep for Git repos with a conclusively old last commit.

use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use super::{Action, ApplyOutcome, Finding, Op, apply_filesystem_finding, dir_size};
use crate::safety::{Ctx, build_process_cwds, escalate};

use super::project::{iso_days_ago, owning_repo, repo_has_active_build, repo_last_commit};

pub struct NodeModules;

impl Op for NodeModules {
    fn name(&self) -> &'static str {
        "node-modules"
    }

    fn scan(&self, ctx: &Ctx) -> Result<Vec<Finding>> {
        let process_cwds = build_process_cwds().context("cannot verify build-process liveness")?;
        self.scan_with_process_cwds(ctx, &process_cwds)
    }

    fn apply(&self, findings: &[Finding], ctx: &Ctx) -> Result<ApplyOutcome> {
        self.apply_with_process_cwds(findings, ctx, build_process_cwds())
    }
}

impl NodeModules {
    fn scan_with_process_cwds(&self, ctx: &Ctx, process_cwds: &[PathBuf]) -> Result<Vec<Finding>> {
        let cutoff = iso_days_ago(ctx.active_days);
        let mut groups: BTreeMap<PathBuf, Vec<PathBuf>> = BTreeMap::new();
        for root in &ctx.roots {
            if root.is_dir() {
                for path in find_node_modules(root) {
                    if let Some(owner) = owning_repo(&path) {
                        groups.entry(owner).or_default().push(path);
                    }
                }
            }
        }

        let mut findings = Vec::new();
        let mut active = 0usize;
        let mut build_active = 0usize;
        let mut unproven = 0usize;
        for (owner, targets) in groups {
            if repo_has_active_build(&owner, process_cwds) {
                build_active = build_active.saturating_add(targets.len());
                continue;
            }
            // Unknown activity is never deletion authority: skip the repo instead of
            // failing the whole category, so one unreadable repo cannot hide the rest.
            let last_commit = match repo_last_commit(&owner) {
                Ok(date) => date,
                Err(error) => {
                    unproven += targets.len();
                    if !ctx.json {
                        ctx.diagnostic("warn", format!("skipping {}: {error:#}", owner.display()));
                    }
                    continue;
                }
            };
            if last_commit > cutoff {
                active += targets.len();
                continue;
            }
            for target in targets {
                let size = dir_size(&target)?;
                findings.push(Finding::new(
                    "stale node_modules",
                    Some(target),
                    size,
                    format!(
                        "repo last committed {last_commit}; lockfile: {}",
                        has_lockfile(&owner)
                    ),
                    escalate(5, size),
                    Action::Trash,
                ));
            }
        }
        if active > 0 && !ctx.json {
            ctx.diagnostic(
                "info",
                format!("skipping {active} node_modules in active repos"),
            );
        }
        if build_active > 0 && !ctx.json {
            ctx.diagnostic(
                "info",
                format!("skipping {build_active} node_modules because a build process is active"),
            );
        }
        if unproven > 0 && !ctx.json {
            ctx.diagnostic(
                "info",
                format!("skipping {unproven} node_modules whose Git activity is unproven"),
            );
        }
        Ok(findings)
    }

    fn apply_with_process_cwds(
        &self,
        findings: &[Finding],
        ctx: &Ctx,
        process_cwds: Result<Vec<PathBuf>>,
    ) -> Result<ApplyOutcome> {
        let cutoff = iso_days_ago(ctx.active_days);
        let mut outcome = ApplyOutcome::new(self.name());
        let process_cwds = match process_cwds {
            Ok(process_cwds) => process_cwds,
            Err(error) => {
                outcome.fail(error.context("cannot verify build-process liveness"));
                return Ok(outcome);
            }
        };
        for finding in findings {
            if !matches!(finding.action, Action::Trash | Action::Shred) {
                continue;
            }
            let Some(path) = finding.target() else {
                outcome.fail(anyhow::anyhow!(
                    "node_modules finding missing internal target"
                ));
                break;
            };
            if !path.exists() {
                outcome
                    .summary
                    .notes
                    .push(format!("skipped vanished {}", path.display()));
                continue;
            }
            let result = (|| -> Result<String> {
                let owner = owning_repo(path).ok_or_else(|| {
                    anyhow::anyhow!("cannot prove Git owner for {}", path.display())
                })?;
                if repo_has_active_build(&owner, &process_cwds) {
                    anyhow::bail!(
                        "build process active in {}; refusing {}",
                        owner.display(),
                        path.display()
                    );
                }
                let last_commit = repo_last_commit(&owner)?;
                if last_commit > cutoff {
                    anyhow::bail!(
                        "repo became active after preview; refusing {}",
                        path.display()
                    );
                }
                apply_filesystem_finding(self.name(), finding, ctx)?;
                Ok(format!(
                    "{} {}",
                    if finding.action == Action::Shred {
                        "permanently deleted"
                    } else {
                        "trashed"
                    },
                    path.display()
                ))
            })();
            match result {
                Ok(note) => outcome.record(finding, note),
                Err(error) => {
                    outcome.fail(error);
                    break;
                }
            }
        }
        Ok(outcome)
    }
}

fn find_node_modules(root: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let mut entries = walkdir::WalkDir::new(root).follow_links(false).into_iter();
    while let Some(result) = entries.next() {
        let Ok(entry) = result else { continue };
        if !entry.file_type().is_dir() {
            continue;
        }
        if entry.file_name() == ".git" {
            entries.skip_current_dir();
            continue;
        }
        if entry.file_name() == "node_modules" {
            found.push(entry.path().to_path_buf());
            entries.skip_current_dir();
        }
    }
    found
}

pub(crate) fn has_lockfile(root: &Path) -> &'static str {
    for file in [
        "pnpm-lock.yaml",
        "package-lock.json",
        "yarn.lock",
        "bun.lockb",
        "bun.lock",
    ] {
        if root.join(file).exists() {
            return file;
        }
    }
    "none"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp(name: &str) -> PathBuf {
        let path = std::env::temp_dir().join(format!("devtrim-{name}-{}", std::process::id()));
        crate::ops::remove_test_path(&path);
        std::fs::create_dir_all(&path).unwrap();
        path
    }

    fn context(home: PathBuf) -> Ctx {
        Ctx {
            yes: true,
            yolo: false,
            json: false,
            roots: vec![home.clone()],
            active_days: 30,
            protect: Vec::new(),
            journal_path: home.join("journal.jsonl"),
            home,
            interactive: false,
            diagnostic_output: crate::safety::DiagnosticOutput::Capture,
            diagnostics: Default::default(),
            journal_errors: Default::default(),
        }
    }

    #[test]
    fn prunes_dependency_and_git_trees() {
        let base = temp("prune");
        let outer = base.join("app/node_modules");
        std::fs::create_dir_all(outer.join("nested/node_modules")).unwrap();
        std::fs::create_dir_all(base.join("app/.git/hidden/node_modules")).unwrap();
        let found = find_node_modules(&base);
        assert_eq!(found, vec![outer]);
        crate::ops::remove_test_path(base);
    }

    #[test]
    fn lockfile_detection() {
        let base = temp("lockfile");
        std::fs::write(base.join("package-lock.json"), "{}").unwrap();
        assert_eq!(has_lockfile(&base), "package-lock.json");
        crate::ops::remove_test_path(base);
    }

    #[test]
    fn apply_rejects_target_without_git_owner() {
        let home = temp("orphan-apply");
        let target = home.join("orphan/node_modules");
        std::fs::create_dir_all(&target).unwrap();
        let sentinel = target.join("sentinel");
        std::fs::write(&sentinel, "keep").unwrap();
        let finding = Finding::new(
            "forged orphan node_modules",
            Some(target),
            4,
            "test",
            9,
            Action::Shred,
        );
        let ctx = context(home.clone());

        let outcome = NodeModules
            .apply_with_process_cwds(&[finding], &ctx, Ok(Vec::new()))
            .unwrap();

        assert_eq!(outcome.summary.items_touched, 0);
        assert_eq!(outcome.errors.len(), 1);
        assert!(outcome.errors[0].contains("cannot prove Git owner"));
        assert!(sentinel.exists());
        crate::ops::remove_test_path(home);
    }

    #[test]
    fn active_build_cwd_skips_repo_and_refuses_apply() {
        let home = temp("build-active");
        let repo = home.join("project");
        let target = repo.join("node_modules");
        std::fs::create_dir_all(repo.join(".git")).unwrap();
        std::fs::create_dir_all(&target).unwrap();
        let sentinel = target.join("sentinel");
        std::fs::write(&sentinel, "keep").unwrap();
        let ctx = context(home.clone());
        let process_cwds = vec![repo.join("packages/app")];

        let findings = NodeModules
            .scan_with_process_cwds(&ctx, &process_cwds)
            .unwrap();
        assert!(findings.is_empty());
        assert!(
            ctx.take_diagnostics()
                .iter()
                .any(|message| message.contains("build process is active"))
        );

        let finding = Finding::new(
            "stale node_modules",
            Some(target),
            4,
            "test",
            9,
            Action::Shred,
        );
        let outcome = NodeModules
            .apply_with_process_cwds(&[finding], &ctx, Ok(process_cwds.clone()))
            .unwrap();
        assert_eq!(outcome.summary.items_touched, 0);
        assert!(outcome.errors[0].contains("build process active"));
        assert!(sentinel.exists());

        let mut json_ctx = context(home.clone());
        json_ctx.json = true;
        assert!(
            NodeModules
                .scan_with_process_cwds(&json_ctx, &process_cwds)
                .unwrap()
                .is_empty()
        );
        assert!(json_ctx.take_diagnostics().is_empty());
        crate::ops::remove_test_path(home);
    }
}
