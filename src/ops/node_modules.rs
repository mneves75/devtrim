    /// A `node_modules` below corroborated build output is part of that
    /// output: Next.js `output: 'standalone'` copies one into
    /// `.next/standalone`, and a stale repository left inside a Cargo
    /// `target` (a test fixture) is generated too. Offering them would count
    /// the same bytes twice in `purge`, and the build output's own gates,
    /// not a `node_modules` finding, decide whether it goes.
    #[test]
    fn a_node_modules_inside_build_output_belongs_to_that_output() {
        let fixture = crate::ops::TestFixture::new("devtrim-node-build-output");
        std::fs::create_dir_all(fixture.path()).unwrap();
        let home = fixture.path().canonicalize().unwrap();
        let web = home.join("web");
        init_old_git_repo(&web).unwrap();
        std::fs::write(web.join("package.json"), "{}").unwrap();
        let own = web.join("node_modules");
        std::fs::create_dir_all(own.join("pkg")).unwrap();
        let standalone = web.join(".next/standalone/node_modules");
        std::fs::create_dir_all(standalone.join("pkg")).unwrap();
        std::fs::write(standalone.join("pkg/index.js"), "x").unwrap();
        let tool = home.join("tool");
        init_old_git_repo(&tool).unwrap();
        std::fs::write(tool.join("Cargo.toml"), "[package]").unwrap();
        let leaked = tool.join("target/fixture");
        init_old_git_repo(&leaked).unwrap();
        std::fs::create_dir_all(leaked.join("node_modules/pkg")).unwrap();
        std::fs::write(leaked.join("node_modules/pkg/index.js"), "x").unwrap();
        let ctx = context(home.clone());

        let findings = NodeModules.scan_with_process_cwds(&ctx, &[]).unwrap();
        let paths = findings
            .iter()
            .filter_map(Finding::target)
            .collect::<Vec<_>>();
        assert_eq!(
            paths,
            vec![own.as_path()],
            "PV node_modules/build-output-walk: positive control and exclusions"
        );

        // A scan root inside the repository's build output: the walk starts
        // below `.next`, so only the owner-bounded check can see it.
        let inner = context(web.join(".next"));
        assert!(
            NodeModules
                .scan_with_process_cwds(&inner, &[])
                .unwrap()
                .is_empty(),
            "PV node_modules/build-output-scan: a node_modules inside build output was offered"
        );
        assert!(
            inner
                .take_diagnostics()
                .iter()
                .any(|message| message.contains("inside build output")),
            "the skipped build-output node_modules must be disclosed"
        );

        let forged = Finding::new(
            "stale node_modules",
            Some(standalone.clone()),
            1,
            "test",
            5,
            Action::Trash,
        );
        let outcome = NodeModules
            .apply_with_process_cwds(&[forged], &ctx, Ok(Vec::new()))
            .unwrap();
        assert!(
            outcome.summary.items_touched == 0
                && standalone.join("pkg/index.js").exists()
                && outcome
                    .errors
                    .iter()
                    .any(|error| error.contains("inside build output")),
            "PV node_modules/build-output-apply: {outcome:?}"
        );
    }

