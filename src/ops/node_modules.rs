//! `node_modules` sweep for Git repos with a conclusively old last commit.

use anyhow::{Context, Result};
use colored::Colorize;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use super::{Action, ApplyOutcome, Finding, Op, apply_filesystem_finding, dir_size};
use crate::safety::{Ctx, escalate};

pub struct NodeModules;

impl Op for NodeModules {
    fn name(&self) -> &'static str {
        "node-modules"
    }

    fn scan(&self, ctx: &Ctx) -> Result<Vec<Finding>> {
        let cutoff = iso_days_ago(ctx.active_days);
        let mut groups: BTreeMap<PathBuf, Vec<PathBuf>> = BTreeMap::new();
        for root in &ctx.roots {
            if root.is_dir() {
                for path in find_node_modules(root) {
                    if let Some(owner) = owning_repo(&path) {
                        groups.entry(owner).or_default().push(path);
                    }
                }
            }
        }

        let mut findings = Vec::new();
        let mut active = 0usize;
        let mut unproven = 0usize;
        for (owner, targets) in groups {
            // Unknown activity is never deletion authority: skip the repo instead of
            // failing the whole category, so one unreadable repo cannot hide the rest.
            let last_commit = match repo_last_commit(&owner) {
                Ok(date) => date,
                Err(error) => {
                    unproven += targets.len();
                    if !ctx.json {
                        eprintln!(
                            "{} skipping {}: {error:#}",
                            "warn".yellow(),
                            owner.display()
                        );
                    }
                    continue;
                }
            };
            if last_commit > cutoff {
                active += targets.len();
                continue;
            }
            for target in targets {
                let size = dir_size(&target);
                findings.push(Finding::new(
                    "stale node_modules",
                    Some(target),
                    size,
                    format!(
                        "repo last committed {last_commit}; lockfile: {}",
                        has_lockfile(&owner)
                    ),
                    escalate(5, size),
                    Action::Trash,
                ));
            }
        }
        if active > 0 && !ctx.json {
            eprintln!(
                "{} skipping {active} node_modules in active repos",
                "info".dimmed()
            );
        }
        if unproven > 0 && !ctx.json {
            eprintln!(
                "{} skipping {unproven} node_modules whose Git activity is unproven",
                "info".dimmed()
            );
        }
        Ok(findings)
    }

    fn apply(&self, findings: &[Finding], ctx: &Ctx) -> Result<ApplyOutcome> {
        let cutoff = iso_days_ago(ctx.active_days);
        let mut outcome = ApplyOutcome::new(self.name());
        for finding in findings {
            if !matches!(finding.action, Action::Trash | Action::Shred) {
                continue;
            }
            let Some(path) = finding.target() else {
                outcome.fail(anyhow::anyhow!(
                    "node_modules finding missing internal target"
                ));
                break;
            };
            if !path.exists() {
                outcome
                    .summary
                    .notes
                    .push(format!("skipped vanished {}", path.display()));
                continue;
            }
            let result = (|| -> Result<String> {
                let owner = owning_repo(path).ok_or_else(|| {
                    anyhow::anyhow!("cannot prove Git owner for {}", path.display())
                })?;
                let last_commit = repo_last_commit(&owner)?;
                if last_commit > cutoff {
                    anyhow::bail!(
                        "repo became active after preview; refusing {}",
                        path.display()
                    );
                }
                apply_filesystem_finding(finding, ctx)?;
                Ok(format!(
                    "{} {}",
                    if finding.action == Action::Shred {
                        "permanently deleted"
                    } else {
                        "trashed"
                    },
                    path.display()
                ))
            })();
            match result {
                Ok(note) => outcome.record(finding, note),
                Err(error) => {
                    outcome.fail(error);
                    break;
                }
            }
        }
        Ok(outcome)
    }
}

fn find_node_modules(root: &Path) -> Vec<PathBuf> {
    let mut found = Vec::new();
    let mut entries = walkdir::WalkDir::new(root).follow_links(false).into_iter();
    while let Some(result) = entries.next() {
        let Ok(entry) = result else { continue };
        if !entry.file_type().is_dir() {
            continue;
        }
        if entry.file_name() == ".git" {
            entries.skip_current_dir();
            continue;
        }
        if entry.file_name() == "node_modules" {
            found.push(entry.path().to_path_buf());
            entries.skip_current_dir();
        }
    }
    found
}

fn owning_repo(path: &Path) -> Option<PathBuf> {
    let mut current = path.to_path_buf();
    while current.parent().is_some() {
        current.pop();
        if current.join(".git").exists() {
            return Some(current);
        }
    }
    None
}

fn repo_last_commit(root: &Path) -> Result<String> {
    repo_last_commit_with(root, "git")
}

fn repo_last_commit_with(root: &Path, git: &str) -> Result<String> {
    if !root.join(".git").exists() {
        anyhow::bail!("not a Git repository: {}", root.display());
    }
    // Fixed argv only, and neutralize repository-controlled config that git would
    // otherwise honor while inspecting an untrusted clone.
    let output = Command::new(git)
        .arg("-C")
        .arg(root)
        .args([
            "-c",
            "core.fsmonitor=false",
            "-c",
            "core.hooksPath=/dev/null",
            "--no-optional-locks",
            "log",
            "-1",
            "--format=%cs",
        ])
        .output()
        .with_context(|| format!("cannot inspect Git activity for {}", root.display()))?;
    if !output.status.success() {
        anyhow::bail!("Git activity check failed for {}", root.display());
    }
    let date = String::from_utf8(output.stdout).context("Git returned a non-UTF-8 date")?;
    let date = date.trim();
    if date.len() != 10
        || !date.chars().enumerate().all(|(index, character)| {
            if index == 4 || index == 7 {
                character == '-'
            } else {
                character.is_ascii_digit()
            }
        })
    {
        anyhow::bail!("Git returned an invalid commit date for {}", root.display());
    }
    Ok(date.to_string())
}

pub(crate) fn has_lockfile(root: &Path) -> &'static str {
    for file in [
        "pnpm-lock.yaml",
        "package-lock.json",
        "yarn.lock",
        "bun.lockb",
        "bun.lock",
    ] {
        if root.join(file).exists() {
            return file;
        }
    }
    "none"
}

fn iso_days_ago(days: u32) -> String {
    let seconds = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_secs())
        .unwrap_or(0);
    iso_from_epoch_days(((seconds.saturating_sub(days as u64 * 86_400)) / 86_400) as i64)
}

fn iso_from_epoch_days(days: i64) -> String {
    let days = days + 719_468;
    let era = days.div_euclid(146_097);
    let day_of_era = days.rem_euclid(146_097);
    let year_of_era =
        (day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let year = year_of_era + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let month_prime = (5 * day_of_year + 2) / 153;
    let day = day_of_year - (153 * month_prime + 2) / 5 + 1;
    let month = if month_prime < 10 {
        month_prime + 3
    } else {
        month_prime - 9
    };
    let year = if month <= 2 { year + 1 } else { year };
    format!("{year:04}-{month:02}-{day:02}")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp(name: &str) -> PathBuf {
        let path = std::env::temp_dir().join(format!("devtrim-{name}-{}", std::process::id()));
        crate::ops::remove_test_path(&path);
        std::fs::create_dir_all(&path).unwrap();
        path
    }

    #[test]
    fn iso_dates_are_correct_and_ordered() {
        assert_eq!(iso_from_epoch_days(0), "1970-01-01");
        assert_eq!(iso_from_epoch_days(19_723), "2024-01-01");
        assert!(iso_days_ago(30) < iso_days_ago(1));
    }

    #[test]
    fn finds_owning_repo_and_handles_orphans() {
        let base = temp("owner");
        let project = base.join("project/sub/node_modules");
        std::fs::create_dir_all(&project).unwrap();
        std::fs::create_dir_all(base.join("project/.git")).unwrap();
        assert_eq!(owning_repo(&project), Some(base.join("project")));
        assert_eq!(owning_repo(&base.join("orphan/node_modules")), None);
        crate::ops::remove_test_path(base);
    }

    #[test]
    fn prunes_dependency_and_git_trees() {
        let base = temp("prune");
        let outer = base.join("app/node_modules");
        std::fs::create_dir_all(outer.join("nested/node_modules")).unwrap();
        std::fs::create_dir_all(base.join("app/.git/hidden/node_modules")).unwrap();
        let found = find_node_modules(&base);
        assert_eq!(found, vec![outer]);
        crate::ops::remove_test_path(base);
    }

    #[test]
    fn git_failure_is_not_stale() {
        let base = temp("git-fail");
        std::fs::create_dir_all(base.join(".git")).unwrap();
        assert!(repo_last_commit_with(&base, "/usr/bin/false").is_err());
        crate::ops::remove_test_path(base);
    }

    #[test]
    fn lockfile_detection() {
        let base = temp("lockfile");
        std::fs::write(base.join("package-lock.json"), "{}").unwrap();
        assert_eq!(has_lockfile(&base), "package-lock.json");
        crate::ops::remove_test_path(base);
    }
}
